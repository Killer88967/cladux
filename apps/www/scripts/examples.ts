// Writes src/lib/examples.generated.ts and src/components/demos.generated.tsx:
// one entry per demo file in
// packages/ui/src/<component>/examples/<name>.tsx, keyed by <name>.
// Runs before dev and build, so new demos show up without editing anything.
import { readdir, readFile, writeFile } from "node:fs/promises";

const UI = new URL("../../../packages/ui/src/", import.meta.url);
const OUT = new URL("../src/lib/examples.generated.ts", import.meta.url);

const entries: { name: string; path: string; named?: string }[] = [];
for (const dir of await readdir(UI, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const files = await readdir(new URL(`${dir.name}/examples/`, UI)).catch(() => []);
  for (const file of files) {
    if (!file.endsWith(".tsx")) continue;
    const name = file.slice(0, -4);
    const code = await readFile(new URL(`${dir.name}/examples/${file}`, UI), "utf8");
    // Use the default export, or the first exported function (shadcn's demos do both).
    const named = /^export default/m.test(code)
      ? undefined
      : code.match(/^export function (\w+)/m)?.[1];
    entries.push({ name, path: `${dir.name}/examples/${name}`, named });
  }
}
entries.sort((a, b) => a.name.localeCompare(b.name));

// Two files: the paths, for the server to read each demo's source, and the
// demos themselves, for the browser. The demos go through next/dynamic in a
// client file, so each one is its own chunk and a page downloads only the
// demos it shows.
const source = [
  "// Generated by scripts/examples.ts. Do not edit.",
  "export const examplePaths: Record<string, string> = {",
  ...entries.map((e) => `  "${e.name}": "${e.path}",`),
  "};",
  "",
].join("\n");

await writeFile(
  new URL("../src/components/demos.generated.tsx", import.meta.url),
  [
    "// Generated by scripts/examples.ts. Do not edit.",
    '"use client";',
    "",
    'import dynamic from "next/dynamic";',
    'import type { ComponentType } from "react";',
    "",
    "const demos: Record<string, ComponentType> = {",
    ...entries.map(
      (e) =>
        `  "${e.name}": dynamic(() => import("@cladux/ui/${e.path}").then((m) => m.${e.named ?? "default"})),`,
    ),
    "};",
    "",
    "/** One demo, by its file name. Only the demos a page renders are downloaded. */",
    "export function Demo({ name }: { name: string }) {",
    "  const Component = demos[name];",
    "  return Component ? <Component /> : null;",
    "}",
    "",
  ].join("\n"),
);

await writeFile(OUT, source);
console.log(`examples: ${entries.length} demos`);

// Blocks: components/blocks.generated.tsx, one entry per packages/ui/src/blocks/<name>.tsx.
// Each /view/<name> page shows one block, so they load the same way as the demos.
const { blocks } = await import("../../../packages/ui/src/blocks/_blocks.ts");
const blockId = (name: string) => "Block_" + name.replace(/[^a-zA-Z0-9]/g, "_");
await writeFile(
  new URL("../src/components/blocks.generated.tsx", import.meta.url),
  [
    "// Generated by scripts/examples.ts. Do not edit.",
    '"use client";',
    "",
    'import dynamic from "next/dynamic";',
    'import type { ComponentType } from "react";',
    "",
    "const blocks: Record<string, ComponentType> = {",
    ...blocks.map((b) => `  "${b.name}": dynamic(() => import("@cladux/ui/blocks/${b.name}")),`),
    "};",
    "",
    "/** One block, by name. Only the block a page renders is downloaded. */",
    "export function Block({ name }: { name: string }) {",
    "  const Component = blocks[name];",
    "  return Component ? <Component /> : null;",
    "}",
    "",
  ].join("\n"),
);
console.log(`blocks: ${blocks.length}`);

// Charts: lib/charts.generated.ts, one entry per packages/ui/src/charts/<name>.tsx.
const { charts } = await import("../../../packages/ui/src/charts/_charts.ts");
await writeFile(
  new URL("../src/lib/charts.generated.ts", import.meta.url),
  [
    "// Generated by scripts/examples.ts. Do not edit.",
    'import type { ComponentType } from "react";',
    ...charts.map((c) => `import ${blockId(c.name)} from "@cladux/ui/charts/${c.name}";`),
    "",
    "export const chartComponents: Record<string, ComponentType> = {",
    ...charts.map((c) => `  "${c.name}": ${blockId(c.name)},`),
    "};",
    "",
  ].join("\n"),
);
console.log(`charts: ${charts.length}`);
